"""Build a joined Week 3 feature dataset from six Week 2 probe datasets.

Each input dataset is supplied as ``suite=/path/to/week2_dataset`` and must
contain a ``manifest.jsonl`` (or ``records.jsonl``) plus the referenced NPZ
files.  Labels can be joined from the boundary-task JSONL generated by
``probe.data.extract_boundary_tasks``.

The output keeps one row per state-condition record.  It does not duplicate a
row for each sampled action.  S features are derived from fixed prefixes of
the stored K x H x D action samples, while B is copied from the first-call
feature when available.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import random
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

import numpy as np


DEFAULT_PREFIXES = (1, 4, 8, 16, 32)
S_FEATURE_NAMES = (
    "mean_disagreement",
    "max_disagreement",
    "early_disagreement",
    "late_disagreement",
    "pairwise_rms_median",
    "pairwise_rms_p90",
    "first_step_disagreement",
    "last_step_disagreement",
)
SUITE_ALIASES = {
    "objects": "object",
    "object_layout": "object",
    "lang": "language",
    "langgrape": "language",
}


def normalize_suite(value: str) -> str:
    normalized = value.strip().lower().replace("-", "_").replace(" ", "_")
    return SUITE_ALIASES.get(normalized, normalized)


def safe_id(value: str) -> str:
    return "".join(char if char.isalnum() or char in "._-" else "_" for char in value)


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8-sig") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            try:
                payload = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{line_number}: invalid JSON: {exc}") from exc
            if not isinstance(payload, dict):
                raise ValueError(f"{path}:{line_number}: expected a JSON object")
            rows.append(payload)
    return rows


def find_manifest(dataset_dir: Path, manifest_name: str) -> Path:
    requested = dataset_dir / manifest_name
    if requested.exists():
        return requested
    if manifest_name == "manifest.jsonl":
        fallback = dataset_dir / "records.jsonl"
        if fallback.exists():
            return fallback
    raise FileNotFoundError(
        f"No manifest found in {dataset_dir}; checked {requested}"
    )


def resolve_ref(dataset_dir: Path, value: str | None) -> Path | None:
    if not value:
        return None
    path = Path(value)
    return path if path.is_absolute() else dataset_dir / path


def condition_id(record: dict[str, Any]) -> str:
    return str(record.get("condition_type") or record.get("condition_id") or "")


def task_id(record: dict[str, Any]) -> int:
    try:
        return int(record["task_id"])
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError(f"Record has no integer task_id: {record}") from exc


def base_id(record: dict[str, Any]) -> str:
    return str(record.get("base_id") or f"task{task_id(record):04d}")


def _manifest_label(record: dict[str, Any]) -> dict[str, Any] | None:
    successes = record.get("eval_successes")
    trials = record.get("eval_trials")
    if successes is None or trials is None:
        return None
    return {
        "successes": int(successes),
        "trials": int(trials),
        "source": "manifest",
    }


def load_labels(path: Path | None) -> dict[tuple[str, int, str], dict[str, Any]]:
    if path is None:
        return {}
    result: dict[tuple[str, int, str], dict[str, Any]] = {}
    for row in read_jsonl(path):
        if "suite" not in row or "task_id" not in row:
            raise ValueError(f"{path}: each label row needs suite and task_id")
        suite = normalize_suite(str(row["suite"]))
        current_task_id = int(row["task_id"])
        for condition in ("original", "better", "worse"):
            successes_key = f"{condition}_successes"
            trials_key = f"{condition}_trials"
            if successes_key not in row or trials_key not in row:
                continue
            key = (suite, current_task_id, condition)
            label = {
                "successes": int(row[successes_key]),
                "trials": int(row[trials_key]),
                "source": str(row.get("source_report") or path),
            }
            previous = result.get(key)
            if previous is not None and (
                previous["successes"] != label["successes"]
                or previous["trials"] != label["trials"]
            ):
                raise ValueError(f"Conflicting labels for {key}: {previous} vs {label}")
            result[key] = label
    return result


def load_action_samples(path: Path, record_id: str) -> np.ndarray:
    if not path.exists():
        raise FileNotFoundError(f"{record_id}: action file not found: {path}")
    with np.load(path, allow_pickle=False) as data:
        if "action_samples" not in data:
            raise KeyError(f"{path}: missing action_samples")
        samples = np.asarray(data["action_samples"], dtype=np.float64)
    if samples.ndim != 3:
        raise ValueError(f"{record_id}: expected action samples [K,H,D], got {samples.shape}")
    if not np.isfinite(samples).all():
        raise ValueError(f"{record_id}: action samples contain NaN or Inf")
    return samples


def load_b_feature(path: Path | None, record_id: str) -> np.ndarray | None:
    if path is None:
        return None
    if not path.exists():
        raise FileNotFoundError(f"{record_id}: B feature file not found: {path}")
    with np.load(path, allow_pickle=False) as data:
        if "b_feature" not in data:
            raise KeyError(f"{path}: missing b_feature")
        feature = np.asarray(data["b_feature"], dtype=np.float32)
    if feature.ndim != 1:
        raise ValueError(f"{record_id}: expected 1-D B feature, got {feature.shape}")
    if not np.isfinite(feature).all():
        raise ValueError(f"{record_id}: B feature contains NaN or Inf")
    return feature


def _pairwise_rms(flat_samples: np.ndarray) -> np.ndarray:
    if flat_samples.shape[0] < 2:
        return np.empty(0, dtype=np.float64)
    distances = flat_samples[:, None, :] - flat_samples[None, :, :]
    rms = np.sqrt(np.mean(distances * distances, axis=2))
    upper = np.triu_indices(flat_samples.shape[0], k=1)
    return rms[upper]


def compute_s_features(
    samples: np.ndarray,
    prefix_k: int,
) -> tuple[np.ndarray, dict[str, Any]]:
    if prefix_k < 1 or prefix_k > samples.shape[0]:
        raise ValueError(f"Requested K={prefix_k} for samples with K={samples.shape[0]}")

    prefix = samples[:prefix_k]
    if prefix_k == 1:
        return (
            np.full(len(S_FEATURE_NAMES), np.nan, dtype=np.float32),
            {
                "prefix_k": prefix_k,
                "defined": False,
                "num_pairs": 0,
                "normalization": "identity",
            },
        )

    # The stored pi0.5 action representation is used as-is.  Any learned
    # scaling must be fitted on the training split and is outside this step.
    variance = np.var(prefix, axis=0, ddof=1)
    disagreement_curve = np.sqrt(np.mean(variance, axis=1))
    split = max(1, math.ceil(prefix.shape[1] / 2))
    early = float(np.mean(disagreement_curve[:split]))
    late_values = disagreement_curve[split:]
    late = float(np.mean(late_values)) if late_values.size else float("nan")
    pairwise = _pairwise_rms(prefix.reshape(prefix.shape[0], -1))

    values = np.asarray(
        [
            np.mean(disagreement_curve),
            np.max(disagreement_curve),
            early,
            late,
            np.median(pairwise),
            np.quantile(pairwise, 0.90),
            disagreement_curve[0],
            disagreement_curve[-1],
        ],
        dtype=np.float32,
    )
    return (
        values,
        {
            "prefix_k": prefix_k,
            "defined": True,
            "num_pairs": int(pairwise.size),
            "normalization": "identity",
        },
    )


def parse_dataset_spec(value: str) -> tuple[str, Path]:
    if "=" not in value:
        raise argparse.ArgumentTypeError(
            f"Dataset must use SUITE=PATH syntax, got {value!r}"
        )
    suite, raw_path = value.split("=", 1)
    suite = normalize_suite(suite)
    if not suite or not raw_path:
        raise argparse.ArgumentTypeError(f"Invalid dataset spec: {value!r}")
    return suite, Path(raw_path).expanduser()


def group_id_for(record: dict[str, Any], suite: str) -> str:
    explicit = record.get("group_id")
    if explicit:
        return f"{suite}::{explicit}"
    return f"{suite}::{base_id(record)}"


def make_splits(
    records: list[dict[str, Any]],
    seed: int,
    train_fraction: float,
    validation_fraction: float,
) -> dict[str, Any]:
    if not 0 < train_fraction < 1:
        raise ValueError("train fraction must be in (0, 1)")
    if not 0 <= validation_fraction < 1:
        raise ValueError("validation fraction must be in [0, 1)")
    if train_fraction + validation_fraction >= 1:
        raise ValueError("train + validation fractions must be < 1")

    groups: dict[str, list[str]] = defaultdict(list)
    for record in records:
        groups[str(record["group_id"])].append(str(record["record_id"]))
    group_ids = sorted(groups)
    random.Random(seed).shuffle(group_ids)

    num_groups = len(group_ids)
    num_train = max(1, int(round(num_groups * train_fraction))) if num_groups else 0
    num_validation = (
        max(1, int(round(num_groups * validation_fraction)))
        if num_groups >= 3 and validation_fraction > 0
        else 0
    )
    if num_train + num_validation >= num_groups and num_groups >= 3:
        num_train = max(1, num_groups - num_validation - 1)
    train_groups = group_ids[:num_train]
    validation_groups = group_ids[num_train : num_train + num_validation]
    test_groups = group_ids[num_train + num_validation :]

    group_to_split = {
        group: "train" for group in train_groups
    } | {
        group: "validation" for group in validation_groups
    } | {
        group: "test" for group in test_groups
    }
    record_to_split = {
        record_id: group_to_split[group]
        for group, record_ids in groups.items()
        for record_id in record_ids
    }
    return {
        "split_seed": seed,
        "fractions": {
            "train": train_fraction,
            "validation": validation_fraction,
            "test": 1.0 - train_fraction - validation_fraction,
        },
        "group_key": "suite::base_id_or_group_id",
        "groups": {
            "train": train_groups,
            "validation": validation_groups,
            "test": test_groups,
        },
        "record_ids": {
            split: [
                record_id
                for record in records
                if (record_id := str(record["record_id"])) in record_to_split
                and record_to_split[record_id] == split
            ]
            for split in ("train", "validation", "test")
        },
    }


def write_feature(
    path: Path,
    feature: np.ndarray,
    prefix_k: int,
    metadata: dict[str, Any],
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        path,
        s_feature=np.asarray(feature, dtype=np.float32),
        feature_names=np.asarray(S_FEATURE_NAMES),
        prefix_k=np.asarray(prefix_k, dtype=np.int64),
        defined=np.asarray(bool(metadata["defined"])),
        num_pairs=np.asarray(int(metadata["num_pairs"]), dtype=np.int64),
        normalization=np.asarray(str(metadata["normalization"])),
    )


def write_b_feature(path: Path, feature: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        path,
        b_feature=np.asarray(feature, dtype=np.float32),
        feature_shape=np.asarray(feature.shape, dtype=np.int64),
    )


def write_labels_csv(path: Path, records: list[dict[str, Any]]) -> None:
    fields = [
        "record_id",
        "suite",
        "task_id",
        "base_id",
        "group_id",
        "condition_id",
        "eval_successes",
        "eval_trials",
        "eval_success_rate",
        "label_source",
    ]
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for record in records:
            writer.writerow({field: record.get(field) for field in fields})


def write_protocol(
    path: Path,
    datasets: list[tuple[str, Path]],
    labels_path: Path | None,
    prefixes: tuple[int, ...],
    args: argparse.Namespace,
) -> None:
    lines = [
        "# Week 3 Feature Dataset",
        "",
        "This dataset has one row per state-condition record. Conditions belonging "
        "to the same group stay together in the fixed split.",
        "",
        "## Inputs",
        "",
        "| suite | Week2 dataset |",
        "|---|---|",
    ]
    lines.extend(f"| {suite} | `{path}` |" for suite, path in datasets)
    lines.extend(
        [
            "",
            f"- Label source: `{labels_path}`" if labels_path else "- Label source: manifest fields when present",
            f"- S prefixes: `{','.join(str(value) for value in prefixes)}`",
            "- S normalization: `identity`; no scale was fitted during post-processing.",
            "- B: copied from the first-call Week2 feature when present.",
            "- K=1 disagreement features are `NaN` and marked undefined.",
            f"- Split seed: `{args.split_seed}`; group split is `suite::base_id_or_group_id`.",
            "",
            "## S feature order",
            "",
            "| index | feature |",
            "|---:|---|",
        ]
    )
    lines.extend(f"| {index} | `{name}` |" for index, name in enumerate(S_FEATURE_NAMES))
    lines.extend(
        [
            "",
            "The action samples remain referenced from the source Week2 datasets; "
            "they are not duplicated into this output.",
            "",
        ]
    )
    path.write_text("\n".join(lines), encoding="utf-8")


def build_dataset(args: argparse.Namespace) -> dict[str, Any]:
    dataset_specs = [parse_dataset_spec(value) for value in args.dataset]
    if not dataset_specs:
        raise ValueError("At least one --dataset SUITE=PATH is required")
    prefixes = tuple(sorted(set(args.k_prefixes)))
    if not prefixes or any(value < 1 for value in prefixes):
        raise ValueError("k-prefixes must contain positive integers")
    labels_path = Path(args.labels).expanduser() if args.labels else None
    labels = load_labels(labels_path)
    output_dir = Path(args.output_dir).expanduser()
    output_dir.mkdir(parents=True, exist_ok=True)

    all_records: list[dict[str, Any]] = []
    seen_record_ids: set[str] = set()
    missing_labels: list[str] = []
    missing_b: list[str] = []
    shape_counts: Counter[tuple[int, ...]] = Counter()
    suite_counts: Counter[str] = Counter()
    condition_counts: Counter[str] = Counter()
    b_matrix_rows: list[np.ndarray] = []
    b_matrix_ids: list[str] = []
    s_matrix: dict[int, list[np.ndarray]] = {prefix: [] for prefix in prefixes}
    s_matrix_ids: dict[int, list[str]] = {prefix: [] for prefix in prefixes}

    for suite, dataset_dir in dataset_specs:
        dataset_dir = dataset_dir.resolve()
        manifest_path = find_manifest(dataset_dir, args.manifest_name)
        source_records = read_jsonl(manifest_path)
        for source_record in source_records:
            source_record_id = str(source_record.get("record_id") or "")
            if not source_record_id:
                raise ValueError(f"{manifest_path}: record has empty record_id")
            global_record_id = f"{suite}__{safe_id(source_record_id)}"
            if global_record_id in seen_record_ids:
                raise ValueError(f"Duplicate output record_id: {global_record_id}")
            seen_record_ids.add(global_record_id)

            action_ref = (
                source_record.get("action_samples_path")
                or source_record.get("actions_path")
            )
            action_path = resolve_ref(dataset_dir, str(action_ref) if action_ref else None)
            if action_path is None:
                raise KeyError(f"{global_record_id}: missing action_samples_path")
            samples = load_action_samples(action_path, global_record_id)
            shape_counts[tuple(int(value) for value in samples.shape)] += 1
            if max(prefixes) > samples.shape[0]:
                raise ValueError(
                    f"{global_record_id}: requested K={max(prefixes)}, "
                    f"but stored samples have K={samples.shape[0]}"
                )

            b_ref = source_record.get("b_feature_path")
            b_path = resolve_ref(dataset_dir, str(b_ref) if b_ref else None)
            b_feature = load_b_feature(b_path, global_record_id)
            if b_feature is None:
                missing_b.append(global_record_id)
            else:
                output_b_ref = Path("features") / "B" / f"{global_record_id}.npz"
                write_b_feature(output_dir / output_b_ref, b_feature)
                b_matrix_rows.append(b_feature)
                b_matrix_ids.append(global_record_id)

            current_task_id = task_id(source_record)
            current_condition = condition_id(source_record)
            if not current_condition:
                raise ValueError(f"{global_record_id}: empty condition_id")
            label = labels.get((suite, current_task_id, current_condition))
            if label is None:
                label = _manifest_label(source_record)
            if label is None:
                missing_labels.append(global_record_id)
                successes = trials = rate = None
                label_source = None
            else:
                successes = int(label["successes"])
                trials = int(label["trials"])
                if trials <= 0 or successes < 0 or successes > trials:
                    raise ValueError(f"{global_record_id}: invalid label {label}")
                rate = successes / trials
                label_source = str(label["source"])

            output_record: dict[str, Any] = {
                "record_id": global_record_id,
                "source_record_id": source_record_id,
                "suite": suite,
                "task_id": current_task_id,
                "base_id": base_id(source_record),
                "group_id": group_id_for(source_record, suite),
                "condition_id": current_condition,
                "instruction": source_record.get("instruction"),
                "category": source_record.get("category"),
                "difficulty": source_record.get("difficulty"),
                "source_dataset_dir": str(dataset_dir),
                "source_manifest": str(manifest_path),
                "source_observation_path": source_record.get("observation_path")
                or source_record.get("obs_path"),
                "source_action_samples_path": str(action_ref),
                "source_b_feature_path": b_ref,
                "b_feature_path": (
                    str(Path("features") / "B" / f"{global_record_id}.npz")
                    if b_feature is not None
                    else None
                ),
                "s_feature_paths": {},
                "s_feature_metadata": {},
                "probe_sample_count": int(samples.shape[0]),
                "action_sample_shape": list(samples.shape),
                "eval_successes": successes,
                "eval_trials": trials,
                "eval_success_rate": rate,
                "label_source": label_source,
            }

            for prefix in prefixes:
                feature, metadata = compute_s_features(samples, prefix)
                feature_ref = (
                    Path("features") / "S" / f"K{prefix}" / f"{global_record_id}.npz"
                )
                write_feature(output_dir / feature_ref, feature, prefix, metadata)
                output_record["s_feature_paths"][str(prefix)] = str(feature_ref)
                output_record["s_feature_metadata"][str(prefix)] = metadata
                s_matrix[prefix].append(feature)
                s_matrix_ids[prefix].append(global_record_id)

            all_records.append(output_record)
            suite_counts[suite] += 1
            condition_counts[current_condition] += 1

    if args.require_labels and missing_labels:
        raise ValueError(
            f"{len(missing_labels)} records have no labels; first={missing_labels[:5]}. "
            "Use --allow-missing-labels to build a feature-only dataset."
        )
    if args.require_b and missing_b:
        raise ValueError(
            f"{len(missing_b)} records have no B feature; first={missing_b[:5]}. "
            "Remove --require-b only for an S-only dataset."
        )

    all_records.sort(key=lambda record: str(record["record_id"]))
    manifest_path = output_dir / "manifest.jsonl"
    with manifest_path.open("w", encoding="utf-8", newline="\n") as handle:
        for record in all_records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")

    if b_matrix_rows:
        b_matrix = np.stack(b_matrix_rows)
        np.savez_compressed(
            output_dir / "features" / "B_matrix.npz",
            record_ids=np.asarray(b_matrix_ids),
            b_features=b_matrix,
        )
    for prefix in prefixes:
        if s_matrix[prefix]:
            np.savez_compressed(
                output_dir / "features" / f"S_K{prefix}_matrix.npz",
                record_ids=np.asarray(s_matrix_ids[prefix]),
                s_features=np.stack(s_matrix[prefix]),
                feature_names=np.asarray(S_FEATURE_NAMES),
            )

    splits = make_splits(
        all_records,
        seed=args.split_seed,
        train_fraction=args.train_fraction,
        validation_fraction=args.validation_fraction,
    )
    (output_dir / "splits.json").write_text(
        json.dumps(splits, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    write_labels_csv(output_dir / "labels.csv", all_records)
    write_protocol(output_dir / "protocol.md", dataset_specs, labels_path, prefixes, args)

    by_suite_condition: dict[str, dict[str, dict[str, int]]] = defaultdict(dict)
    for suite in sorted({str(record["suite"]) for record in all_records}):
        for condition in sorted(
            {str(record["condition_id"]) for record in all_records if record["suite"] == suite}
        ):
            subset = [
                record
                for record in all_records
                if record["suite"] == suite and record["condition_id"] == condition
            ]
            labeled = [record for record in subset if record["eval_trials"] is not None]
            by_suite_condition[suite][condition] = {
                "records": len(subset),
                "labeled_records": len(labeled),
                "successes_sum": sum(
                    int(record["eval_successes"]) for record in labeled
                ),
                "trials_sum": sum(int(record["eval_trials"]) for record in labeled),
            }

    summary = {
        "num_records": len(all_records),
        "num_groups": len({str(record["group_id"]) for record in all_records}),
        "suites": dict(sorted(suite_counts.items())),
        "conditions": dict(sorted(condition_counts.items())),
        "action_shapes": {
            "x".join(str(value) for value in shape): count
            for shape, count in sorted(shape_counts.items())
        },
        "missing_labels": len(missing_labels),
        "missing_b_features": len(missing_b),
        "required_labels": bool(args.require_labels),
        "required_b": bool(args.require_b),
        "prefixes": list(prefixes),
        "s_feature_names": list(S_FEATURE_NAMES),
        "by_suite_condition": by_suite_condition,
        "split_group_counts": {
            split: len(groups) for split, groups in splits["groups"].items()
        },
        "split_record_counts": {
            split: len(record_ids) for split, record_ids in splits["record_ids"].items()
        },
    }
    (output_dir / "summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    write_summary_markdown(output_dir / "summary.md", summary, missing_labels, missing_b)
    return summary


def write_summary_markdown(
    path: Path,
    summary: dict[str, Any],
    missing_labels: list[str],
    missing_b: list[str],
) -> None:
    lines = [
        "# Week 3 Dataset Summary",
        "",
        f"- Records: **{summary['num_records']}**",
        f"- Groups: **{summary['num_groups']}**",
        f"- Missing labels: **{summary['missing_labels']}**",
        f"- Missing B features: **{summary['missing_b_features']}**",
        "",
        "## Records by suite",
        "",
        "| suite | records |",
        "|---|---:|",
    ]
    lines.extend(
        f"| {suite} | {count} |"
        for suite, count in sorted(summary["suites"].items())
    )
    lines.extend(
        [
            "",
            "## Labels by suite and condition",
            "",
            "| suite | condition | records | labeled | successes | trials | rate |",
            "|---|---|---:|---:|---:|---:|---:|",
        ]
    )
    for suite, conditions in sorted(summary["by_suite_condition"].items()):
        for condition, values in sorted(conditions.items()):
            trials = values["trials_sum"]
            rate = values["successes_sum"] / trials if trials else None
            rate_text = f"{rate:.4f}" if rate is not None else "n/a"
            lines.append(
                f"| {suite} | {condition} | {values['records']} | "
                f"{values['labeled_records']} | {values['successes_sum']} | "
                f"{trials} | {rate_text} |"
            )
    lines.extend(
        [
            "",
            "## Fixed split",
            "",
            "| split | groups | records |",
            "|---|---:|---:|",
        ]
    )
    for split in ("train", "validation", "test"):
        lines.append(
            f"| {split} | {summary['split_group_counts'][split]} | "
            f"{summary['split_record_counts'][split]} |"
        )
    if missing_labels:
        lines.extend(["", "## Missing labels (first 20)", ""])
        lines.extend(f"- `{record_id}`" for record_id in missing_labels[:20])
    if missing_b:
        lines.extend(["", "## Missing B features (first 20)", ""])
        lines.extend(f"- `{record_id}`" for record_id in missing_b[:20])
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


